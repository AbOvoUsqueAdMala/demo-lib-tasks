CREATE TABLE extension_az_orders (
    id UUID PRIMARY KEY,
    description VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'REGISTERED', 'FETCHED', 'SENT', 'FAILED')),
    external_id VARCHAR(200),
    payload TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);

CREATE TABLE extension_az_order_task_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES extension_az_orders (id),
    task_name VARCHAR(40) NOT NULL,
    outcome VARCHAR(20) NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE')),
    response TEXT,
    error VARCHAR(500),
    performed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX extension_az_order_task_results_order_idx ON extension_az_order_task_results (order_id, id);
